export async function loadPricingConfig(): Promise<PricingConfig> {
  const base = import.meta.env.VITE_API_URL ?? '/api'
  try {
    const res = await fetch(`${base}/construct/pricing-config`)
    if (res.ok) {
      const data = await res.json()
      return { ...defaultPricingConfig, ...data }
    }
  } catch {
    // В автономном режиме используем гарантированно полный дефолтный конфиг
  }
  return defaultPricingConfig
}
